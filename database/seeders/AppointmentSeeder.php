<?php

namespace Database\Seeders;

use Illuminate\Database\Seeder;
use App\Models\Partner\Partner;
use App\Models\User\User;
use App\Models\Appointment\Appointment;
use App\Models\Appointment\AppointmentDetail;
use App\Models\FCH\Common\TimeSlot\TimeSlot;
use Illuminate\Support\Str;
use Carbon\Carbon;

class AppointmentSeeder extends Seeder
{
    /**
     * Run the database seeds.
     */
    public function run(): void
    {
        $users = User::all();
        $timeSlots = TimeSlot::where('is_active', true)->get();

        if ($users->isEmpty() || $timeSlots->isEmpty()) {
            return;
        }

        // Create exactly 10 appointments
        for ($i = 0; $i < 10; $i++) {
            $scheduledBy = $users->random();
            $assignedFor = $users->random();
            $timeSlot = $timeSlots->random();
            $appointmentDate = Carbon::now()->addDays(rand(1, 30))->format('Y-m-d');
            $fullDateTime = $appointmentDate . ' ' . $timeSlot->start_time;

            $status = $this->getRandomStatus();

            $appointment = Appointment::create([
                'appointment_code' => 'APT-' . strtoupper(Str::random(8)),
                'scheduled_by' => $scheduledBy->id,
                'assigned_for' => $assignedFor->id,
                'subject' => 'Seeded Meeting ' . ($i + 1),
                'description' => 'Discussion regarding project details.',
                'appointment_date' => $fullDateTime,
                'timezone' => 'UTC',
                'duration_minutes' => 60,
                'status' => $status,
                'meeting_type' => $this->getRandomMeetingType(),
                'location' => 'Online via Microsoft Teams',
                'remarks' => 'Generated by seeder.',
            ]);

            // Create appointment detail
            AppointmentDetail::create([
                'appointment_id' => $appointment->id,
                'scheduled_by' => $scheduledBy->id,
                'assigned_for' => $assignedFor->id,
                'time_slot_id' => $timeSlot->id,
                'appointment_date' => $appointmentDate,
                'status' => $status === Appointment::STATUS_PENDING ? AppointmentDetail::STATUS_PENDING : AppointmentDetail::STATUS_CONFIRMED,
            ]);
        }
    }

    private function getRandomStatus()
    {
        $statuses = [
            Appointment::STATUS_PENDING,
            Appointment::STATUS_CONFIRMED,
            Appointment::STATUS_REJECTED,
            Appointment::STATUS_RESCHEDULED,
            Appointment::STATUS_COMPLETED,
            Appointment::STATUS_CANCELLED,
        ];
        return $statuses[array_rand($statuses)];
    }

    private function getRandomMeetingType()
    {
        $types = [
            Appointment::MEETING_TYPE_INITIAL_CONSULTATION,
            Appointment::MEETING_TYPE_FOLLOWUP_MEETING,
            Appointment::MEETING_TYPE_BUSINESS_REVIEW,
            Appointment::MEETING_TYPE_TECHNICAL_SUPPORT,
            Appointment::MEETING_TYPE_FEEDBACK_SESSION,
            Appointment::MEETING_TYPE_PARTNERSHIP_MEETING,
        ];
        return $types[array_rand($types)];
    }
}
